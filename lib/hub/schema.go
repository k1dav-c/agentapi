// schemaPrefixes name the types of the dispatch's packages apart from the
// hub's, whose names they share (host.Job and dispatch.Job).
var schemaPrefixes = map[string]string{
	reflect.TypeFor[dispatch.Job]().PkgPath():  "Dispatch",
	reflect.TypeFor[host.Job]().PkgPath():      "Launcher",
	reflect.TypeFor[github.Issue]().PkgPath():  "GitHub",
	reflect.TypeFor[jsonapi.Error]().PkgPath(): "Dispatch",
}

// schemaNamer is huma's namer, with the prefix of the type's package.
func schemaNamer(t reflect.Type, hint string) string {
	name := huma.DefaultSchemaNamer(t, hint)
	base := t
	for base.Kind() == reflect.Pointer || base.Kind() == reflect.Slice || base.Kind() == reflect.Array || base.Kind() == reflect.Map {
		base = base.Elem()
	}
	if prefix, ok := schemaPrefixes[base.PkgPath()]; ok && base.Name() != "" {
		return prefix + name
	}
	return name
}

// hubLimits are the limits of what the hub takes, which the page shows
// and checks before it sends.
var hubLimits = []struct {
	name  string
	value int
	doc   string
}{
	{"max_favorites", maxFavorites, "The most favorites the hub keeps."},
	{"max_favorite_title", maxFavoriteTitle, "The longest favorite title, in characters."},
	{"max_favorite_text", maxFavoriteText, "The longest favorite text, in characters."},
	{"max_favorite_id", maxFavoriteID, "The longest favorite ID."},
	{"max_group_name", maxGroupName, "The longest group name, in characters."},
}

// limitsSchema is HubLimits: each limit a constant.
func limitsSchema() *huma.Schema {
	schema := &huma.Schema{
		Type:                 huma.TypeObject,
		Description:          "The limits of what the hub takes; the page's generated types have their values (hubLimits).",
		Properties:           map[string]*huma.Schema{},
		AdditionalProperties: false,
	}
	for _, limit := range hubLimits {
		schema.Required = append(schema.Required, limit.name)
		schema.Properties[limit.name] = &huma.Schema{Type: huma.TypeInteger, Description: limit.doc, Extensions: map[string]any{"const": limit.value}}
	}
	return schema
}

// Schema is the hub's schema: an OpenAPI document with the wire types in
// its components and no paths.
func Schema() ([]byte, error) {
	registry := huma.NewMapRegistry("#/components/schemas/", schemaNamer)
	registry.RegisterTypeAlias(reflect.TypeFor[instanceapi.SummaryBody](), reflect.TypeFor[summaryRef]())
	for _, t := range wireTypes {
		registry.Schema(t, true, "")
	}
	registry.Map()["HubLimits"] = limitsSchema()
	doc := map[string]any{
		"openapi": "3.1.0",
		"info": map[string]any{
			"title":       "AgentAPI hub",
			"version":     "1",
			"description": "What agentapi hub serve and its page send each other: the bodies of its API and the data of its events (HubEvents, by event name). Generated by make gen from lib/hub; the API's routes are in docs/hub.md.",
		},
		"paths":      map[string]any{},
		"components": map[string]any{"schemas": registry.Map()},
	}
	var out bytes.Buffer
	encoder := json.NewEncoder(&out)
	encoder.SetEscapeHTML(false)
	encoder.SetIndent("", "  ")
	if err := encoder.Encode(doc); err != nil {
		return nil, err
	}
	return out.Bytes(), nil
}
