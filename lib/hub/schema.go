// The hub's API isn't huma's (it serves it with chi), so openapi.json
// doesn't have it: Schema describes what the hub and its page send each
// other, for the page's types (chat/src/lib/hub-schema.ts, from
// hub-schema.json, which make gen writes and TestHubSchema checks).

// summaryRef stands for an instance's summary in the hub's schema: the
// page reads it with the AgentAPI's own types (openapi.json), so the
// hub's schema doesn't have them twice.
type summaryRef struct{}

func (summaryRef) Schema(huma.Registry) *huma.Schema {
	return &huma.Schema{
		Type:                 huma.TypeObject,
		Description:          "The instance's latest summary: SummaryBody of the AgentAPI's schema (openapi.json).",
		AdditionalProperties: true,
	}
}

